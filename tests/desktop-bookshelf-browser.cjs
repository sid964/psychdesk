'use strict';
const assert=require('node:assert/strict');
const {chromium}=require('playwright');
(async()=>{
 const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
 const context=await browser.newContext({viewport:{width:1440,height:900},serviceWorkers:'block'});
 const page=await context.newPage();
 try{
  await page.goto('http://127.0.0.1:8765/',{waitUntil:'domcontentloaded'});
  await page.locator('.desktop-bookshelf').waitFor({timeout:20000});
  assert.match(await page.locator('.desktop-bookshelf').innerText(),/Biological Psychology/);
  assert.match(await page.locator('.desktop-bookshelf').innerText(),/Bookshelf/);
  assert.match(await page.locator('.desktop-bookshelf').innerText(),/Psychology reference books/);
  assert.match(await page.locator('.desktop-bookshelf').innerText(),/Reference collection/);
  assert.equal(await page.locator('.desktop-bookshelf').locator('text=My Drive books').count(),0);
  assert.equal(await page.locator('button[data-tab="files"].desk-add-book').count(),0);
  await page.locator('[data-book-suggest="open"]').click();
  await page.locator('#modalRoot').getByText('PDF suggestions are not open yet.').waitFor({timeout:5000}).catch(async()=>{
   assert.match(await page.locator('#modalRoot').innerText(),/private upload form/);
  });
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('.desktop-rail .rail-link').count(),8);
  await page.locator('.academic-rail-toggle').click();
  assert.equal(await page.locator('.academic-rail-toggle').getAttribute('aria-expanded'),'false');
  await page.locator('.academic-rail-toggle').click();
  assert.equal(await page.locator('.academic-rail-toggle').getAttribute('aria-expanded'),'true');
  assert.equal(await page.locator('button[data-tab="psychology"], button[data-tab="notes"]').count(),0);
  assert.equal(await page.locator('#settingsBtn').count(),1);
  assert.equal(await page.locator('#themeToggle').count(),1);
  assert.equal(await page.locator('.drive-orbit').count(),0);
  assert.equal(await page.locator('.garden-landing').count(),0);
  await page.locator('.desktop-rail [data-tab="tools"]').click();
  await page.locator('.desktop-tool-home').waitFor();
  const tools=await page.locator('.desktop-tool-home').innerText();
  for(const label of ['Library','Sticky notes','PDF reader','References','Psychology dictionary','Psychology timeline'])assert.ok(tools.includes(label),'Missing '+label);
  assert.ok(!tools.includes('University exams'));
  assert.ok(!tools.includes('Annotated PDF reader'));
  assert.ok(!tools.includes('Fast PDF reader'));
  assert.ok(!tools.includes('Mind maps'));
  await page.locator('.study-tool-launcher[data-tab="dictionary"]').click();
  await page.locator('#psyDictionaryQuery').fill('Neurons');
  await page.waitForTimeout(100);
  assert.match(await page.locator('#psyDefinitionDetail').innerText(),/From your bookshelf/);
  assert.match(await page.locator('#psyDefinitionDetail').innerText(),/Neurons/);
  await page.locator('.desktop-rail [data-tab="focus"]').click();
  await page.locator('.focus-room-intro').waitFor();
  await page.locator('#psychWorldLaunch').waitFor({timeout:10000});
  await page.locator('.desktop-rail [data-tab="tools"]').click();
  await page.locator('.study-tool-launcher[data-tab="reader-fast"]').click();
  await page.locator('.fast-pdf-workspace').waitFor();
  await page.locator('#fastPdfFileInput').setInputFiles({name:'sample.pdf',mimeType:'application/pdf',buffer:Buffer.from('%PDF-1.4\n1 0 obj<</Type/Catalog/Pages 2 0 R>>endobj\n2 0 obj<</Type/Pages/Count 0/Kids[]>>endobj\ntrailer<</Root 1 0 R>>\n%%EOF')});
  await page.locator('#fastPdfFrame').waitFor();
  assert.match(await page.locator('#fastPdfFrame').getAttribute('src'),/^blob:/);
  await page.locator('.desktop-rail [data-tab="today"]').click();
  await page.locator('.desktop-bookshelf').waitFor();
  // Verify the actual shell transition independently of the large companion's content download.
  await page.route('**/biological-psychology-14e.html', route => route.fulfill({
    contentType:'text/html',body:'<!doctype html><html><body><h1>Reader test fixture</h1><a href="#read=chapter1">Chapter one</a></body></html>'
  }));
  await page.evaluate(()=>{window.__shellProbe=document.querySelector('#settingsBtn');});
  const cover=page.locator('.desk-book-cover[href="./biological-psychology-14e.html"]');
  await cover.click();
  const workspace=page.locator('#companionWorkspace');
  await workspace.waitFor();
  const reader=page.frameLocator('#companionFrame');
  await reader.getByRole('heading',{name:'Reader test fixture'}).waitFor();
  assert.match(page.url(),/#companion\/biological-psychology-14e$/);
  assert.equal(await page.evaluate(()=>window.__shellProbe===document.querySelector('#settingsBtn')),true);
  assert.equal(await page.locator('#main').isVisible(),false);
  await page.locator('.companion-tools-toggle').click();
  await page.locator('#companionLookup').fill('Neurons');
  await page.locator('#companionLookupResults').getByText('From Biological Psychology').waitFor();
  await page.locator('.companion-resizer').focus();
  await page.keyboard.press('ArrowLeft');
  assert.equal(await page.locator('.companion-resizer').getAttribute('aria-valuenow'),'340');
  await page.locator('#companionNote').fill('Reader integration smoke note');
  await page.locator('#companionNoteForm button[type=submit]').click();
  await page.locator('#companionNoteStatus').getByText('Saved to Sticky Notes.').waitFor();
  assert.ok(await page.evaluate(()=>window.PsychDeskCore.getData().stickies.some(n=>n.rawText==='Reader integration smoke note')));
  await page.locator('#companionWorkspace .companion-focus').click();
  assert.equal(await page.locator('#companionTools').isVisible(),false);
  assert.equal(await page.locator('.app-shell').evaluate(el=>el.classList.contains('companion-focused')),true);
  await page.locator('#companionWorkspace .companion-focus').click();
  assert.equal(await page.locator('#companionTools').isVisible(),true);
  await page.goBack();
  await page.locator('.desktop-bookshelf').waitFor();
  assert.equal(await workspace.isVisible(),false);
  await page.goForward();
  await workspace.waitFor();
  await reader.getByRole('heading',{name:'Reader test fixture'}).waitFor();
  await reader.getByRole('link',{name:'Chapter one'}).click();
  await page.waitForURL(/#companion\/biological-psychology-14e\/read%3Dchapter1$/);
  await page.reload({waitUntil:'domcontentloaded'});
  await workspace.waitFor();
  await reader.getByRole('heading',{name:'Reader test fixture'}).waitFor();
  await page.waitForFunction(()=>document.querySelector('#companionFrame').contentWindow.location.hash==='#read=chapter1');
  await page.locator('#companionWorkspace .companion-back').click();
  await page.locator('.desktop-bookshelf').waitFor();
  assert.equal(await workspace.isVisible(),false);
  await page.locator('.desk-explore-entry').first().click();
  await page.locator('#modalRoot .academic-exhibit').first().waitFor();
  await page.keyboard.press('Escape');
  // Verify the actual companion in a fresh page, never a reused fixture frame.
  await page.unroute('**/biological-psychology-14e.html');
  const actual=await context.newPage();
  const failures=[];
  actual.on('pageerror',err=>failures.push(String(err)));
  actual.on('response',response=>{if(response.status()>=400&&response.url().includes('biological-psychology'))failures.push(response.status()+' '+response.url());});
  await actual.goto('http://127.0.0.1:8765/#companion/biological-psychology-14e',{waitUntil:'domcontentloaded'});
  try{
    await actual.locator('#companionWorkspace').waitFor();
    const real=actual.frameLocator('#companionFrame');
    await real.locator('#viewport .library').waitFor({timeout:90000});
    assert.match(await real.locator('#viewport').innerText(),/Biological Psychology/);
    await real.locator('#continueBtn').click();
    await actual.waitForURL(/#companion\/biological-psychology-14e\/read%3D/,{timeout:15000});
    const chapterURL=actual.url();
    await actual.reload({waitUntil:'domcontentloaded'});
    await actual.frameLocator('#companionFrame').locator('body[data-screen="reader"]').waitFor({timeout:90000});
    assert.equal(actual.url(),chapterURL);
    await actual.locator('#companionWorkspace .companion-back').click();
    await actual.locator('.desktop-bookshelf').waitFor();
  }catch(err){
    console.error('Actual companion diagnostics:',actual.url(), failures, await Promise.all(actual.frames().map(async frame=>({url:frame.url(),body:await frame.locator('body').innerText({timeout:3000}).then(x=>x.slice(0,1200)).catch(String)}))));
    throw err;
  }finally{await actual.close();}
  console.log('DESKTOP_BOOKSHELF_SMOKE_OK');
 }finally{await context.close();await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});