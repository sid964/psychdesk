/* Generate the static GitHub Pages library catalog from reviewed book packages.
 * No OCR, no network calls, no remote files and no PDF bytes are involved.
 */
'use strict';
const fs=require('node:fs');
const path=require('node:path');
const ROOT=path.resolve(__dirname,'..');
const INPUT=path.join(ROOT,'book-packages');
const OUTPUT=path.join(ROOT,'book-catalog.js');
const idOk=id=>typeof id==='string'&&/^[a-z0-9][a-z0-9-]{0,79}$/.test(id);
const textOk=(value,max=240)=>typeof value==='string'&&value.trim().length>0&&value.length<=max;
function fail(reason){throw Error('Book package invalid: '+reason)}
function validateBook(book){
 if(!book||typeof book!=='object'||Array.isArray(book))fail('book must be an object');
 if(!idOk(book.id)||!textOk(book.title)||!textOk(book.subject)||!textOk(book.author)||!textOk(book.edition))fail('missing or invalid book metadata');
 if(book.description!==undefined&&!textOk(book.description,900))fail('description must be nonempty plain text');
 if(book.pdfOffset!==undefined&&!Number.isSafeInteger(book.pdfOffset))fail('invalid PDF offset');
 if(!Array.isArray(book.chapters)||!book.chapters.length)fail('book needs indexed chapters');
 const chapters=new Set(),sections=new Set();
 for(const chapter of book.chapters){
  if(!chapter||!idOk(chapter.id)||chapters.has(chapter.id)||!textOk(chapter.title)||
     !Array.isArray(chapter.sections)||!chapter.sections.length)fail('invalid or duplicate chapter ID');
  chapters.add(chapter.id);
  for(const section of chapter.sections){
   if(!section||!idOk(section.id)||sections.has(section.id)||!textOk(section.title)||
      !['detailed','guide'].includes(section.kind)||!Array.isArray(section.blocks)||!section.blocks.length)
    fail('invalid/duplicate reading part or missing detailed/guide provenance');
   sections.add(section.id);
   if(section.page!==undefined&&(!Number.isSafeInteger(section.page)||section.page<1||
     section.page+(book.pdfOffset||0)<1||section.page+(book.pdfOffset||0)>100000))fail('invalid page mapping');
   const blocks=new Set();
   for(const block of section.blocks){
    if(!block||!idOk(block.id)||blocks.has(block.id)||!['paragraph','heading','quote'].includes(block.type)||
       !textOk(block.text,12000))fail('invalid or duplicate reading block');
    blocks.add(block.id);
   }
  }
 }
 return book;
}
function loadPackages(folder=INPUT){
 const names=fs.readdirSync(folder).filter(name=>name.endsWith('.json')&&!name.startsWith('_')).sort();
 const ids=new Set(),books=[];
 for(const name of names){
  const file=path.join(folder,name);
  if(fs.statSync(file).size>2500000)fail(name+' exceeds the safe 2.5 MB package limit');
  const book=validateBook(JSON.parse(fs.readFileSync(file,'utf8')));
  if(ids.has(book.id))fail('duplicate book id '+book.id);
  if(name!==book.id+'.json')fail(name+' must match the permanent book id '+book.id);
  ids.add(book.id);books.push(book);
 }
 if(!books.length)fail('no reviewed packages found');
 return books;
}
function renderCatalog(books){
 return '/* Generated by scripts/build-book-catalog.cjs from reviewed book-packages/*.json.\n'+
  ' * Do not edit by hand. The indexed content is a study companion, not a published textbook PDF.\n'+
  ' */\nwindow.PsychDeskBookCatalog = '+JSON.stringify(books,null,1)+';\n';
}
function main(args=process.argv.slice(2)){
 if(args.length!==1||!['--check','--write'].includes(args[0]))throw Error('Usage: node scripts/build-book-catalog.cjs --check | --write');
 const source=renderCatalog(loadPackages());
 if(args[0]==='--check'){
  if(fs.readFileSync(OUTPUT,'utf8')!==source)throw Error('book-catalog.js is stale; regenerate with --write and commit the generated result.');
  console.log('BOOK_CATALOG_VERIFIED: source packages exactly match the shipped indexed books.');
 }else{
  fs.writeFileSync(OUTPUT,source);
  console.log('Wrote '+OUTPUT);
 }
}
if(require.main===module){try{main()}catch(error){console.error(error.message);process.exitCode=1}}
module.exports={validateBook,loadPackages,renderCatalog,main,ROOT,INPUT,OUTPUT};
